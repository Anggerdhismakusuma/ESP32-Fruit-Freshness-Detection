// Returns 0 = Fresh, 1 = Spoiled
// spoiledProbability returns the average Spoiled probability.
static inline uint8_t predictFruit(
    const float input[4],
    float* spoiledProbability = nullptr
) {
    float totalSpoiledProbability = 0.0f;

    for (uint8_t t = 0; t < RF_TREE_COUNT; t++) {
        uint16_t node = pgm_read_word(&RF_ROOTS[t]);

        for (uint8_t step = 0; step < 16; step++) {
            if (node >= RF_NODE_COUNT) break;

            uint8_t feature = pgm_read_byte(&RF_FEATURE[node]);

            if (feature == RF_LEAF) {
                totalSpoiledProbability +=
                    pgm_read_float(&RF_SPOILED_PROB[node]);
                break;
            }

            float threshold =
                pgm_read_float(&RF_THRESHOLD[node]);

            uint16_t child;

            if (input[feature] <= threshold) {
                child = pgm_read_word(&RF_LEFT[node]);
            } else {
                child = pgm_read_word(&RF_RIGHT[node]);
            }

            if (child == RF_NO_CHILD) break;
            node = child;
        }
    }

    float probability =
        totalSpoiledProbability / RF_TREE_COUNT;

    if (spoiledProbability != nullptr) {
        *spoiledProbability = probability;
    }

    // sklearn chooses class 0 when probabilities tie.
    return (probability > 0.5f) ? 1 : 0;
}
